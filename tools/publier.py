#!/usr/bin/env python3
"""Build the public V3/ folder from the private canonical corpus in _prive/V3/.

Rule (Gabriel, 2026-09-26):
- Public = numbered, ordered, LLM-ready files, WITHOUT Gabriel's verbatims.
- Verbatim chapters (09, 18) are excluded entirely.
- Every blockquote in public files is treated as a Gabriel verbatim and replaced
  by a placeholder, unless the previous non-blank line marks it as an LLM
  inference ([INFÉRENCE ...]) or an open question ([OUVERT]).
- _prive/ is never versioned. Edit _prive/V3/, then run this script.

Usage (from the repo root):  python tools/publier.py
"""
import os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_prive", "V3")
DST = os.path.join(ROOT, "V3")
MARKER = ".genere"

EXCLUDED = {
    "09_VERBATIMS_ET_CONCLUSIONS_POUR_CALCUL.md",
    "18_GUIDE_RELECTURE_VERBATIMS.md",
}
EXTRA_FILES = {"README.md", "V3_4dfx_FORMALISATION_LEPTONS.md"}
DIRS = {"calculs", "visuels"}
EXCLUDED_IN_DIRS = {"visuels/JOURNAL_REVISION_VISUELLE.md", "visuels/PROMPTS_VISUELS_V3.md"}
PLACEHOLDER = "> *[Verbatim de Gabriel conservé localement — accessible sous sa supervision.]*"
KEEP_IF_PREV = re.compile(r"\[(INFÉRENCE|INFERENCE|OUVERT)")
NUMBERED = re.compile(r"^\d\d_.+\.md$")


def wanted_top(name):
    if name in EXCLUDED or name.startswith("00_README_V3_HISTORIQUE"):
        return False
    return bool(NUMBERED.match(name)) or name in EXTRA_FILES


def strip_verbatims(text, rel, report):
    lines = text.split("\n")
    out, i = [], 0
    while i < len(lines):
        if lines[i].startswith(">"):
            j = i
            while j < len(lines) and lines[j].startswith(">"):
                j += 1
            prev = next((l for l in reversed(out) if l.strip()), "")
            if KEEP_IF_PREV.search(prev):
                out.extend(lines[i:j])
            else:
                out.append(PLACEHOLDER)
                report.append(f"{rel}:{i+1}: {lines[i][:80]}")
            i = j
        else:
            out.append(lines[i])
            i += 1
    return "\n".join(out)


def main():
    if not os.path.isdir(SRC):
        sys.exit(f"Missing source folder: {SRC}")
    if os.path.exists(DST):
        if not os.path.exists(os.path.join(DST, MARKER)):
            sys.exit("V3/ exists but was not generated by this script (no .genere). Aborting.")
        shutil.rmtree(DST)
    os.makedirs(DST)
    report, copied = [], 0
    for name in sorted(os.listdir(SRC)):
        src = os.path.join(SRC, name)
        if os.path.isdir(src):
            if name not in DIRS:
                continue
            for dp, _, files in os.walk(src):
                for f in sorted(files):
                    rel = os.path.relpath(os.path.join(dp, f), SRC).replace(os.sep, "/")
                    if rel in EXCLUDED_IN_DIRS:
                        continue
                    d = os.path.join(DST, rel)
                    os.makedirs(os.path.dirname(d), exist_ok=True)
                    if f.endswith(".md"):
                        with open(os.path.join(dp, f), encoding="utf-8") as fh:
                            txt = strip_verbatims(fh.read(), rel, report)
                        with open(d, "w", encoding="utf-8", newline="") as fh:
                            fh.write(txt)
                    else:
                        shutil.copy2(os.path.join(dp, f), d)
                    copied += 1
        elif wanted_top(name):
            with open(src, encoding="utf-8") as fh:
                txt = strip_verbatims(fh.read(), name, report)
            with open(os.path.join(DST, name), "w", encoding="utf-8", newline="") as fh:
                fh.write(txt)
            copied += 1
    open(os.path.join(DST, MARKER), "w").close()
    print(f"{copied} files published to V3/, {len(report)} verbatims removed:")
    for r in report:
        print("  -", r)


if __name__ == "__main__":
    main()
